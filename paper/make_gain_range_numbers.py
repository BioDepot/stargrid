#!/usr/bin/env python3
"""Range of the molecule gain over Space Ranger on the bins both report (gain_range_numbers.tex).

    python3 make_gain_range_numbers.py > gain_range_numbers.tex

The record export gives the gain on each slide, and a range (gainLo, gainHi)
whose lower end is the SPATCH whole-slide total against Space Ranger's
published filtered matrix. That matrix does not contain every bin. This script
forms the range from the gains counted on the bins in Space Ranger's matrix:
SPATCH and colorectal from the 8 um comparison on Space Ranger's barcode axis,
ovarian from the comparison of the two raw matrices. Every value is read from
numbers.tex. Kept here until the record export adopts it.

The range over all four slides (gainAllLo, gainAllHi) adds the examined slide:
exGainPct of its comparison with Space Ranger on the genes of the probe set
(examined_agreement_numbers.tex; PI, 2026-11-09: the examined slide is compared
on the probe set's genes, as the other Flex slides are). Once the source split
of that slide is on the same genes (its M equals exSRMass), its T and M must
give the same gain, and srcExGapPct with them.
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
NUMBERS = (HERE / "numbers.tex").read_text()
SOURCES = (HERE / "source_split_numbers.tex").read_text()
EXAMINED = (HERE / "examined_agreement_numbers.tex").read_text()


def exported(name, text=NUMBERS):
    match = re.search(r"\\newcommand\{\\" + name + r"\}\{([0-9.]+)\}", text)
    if not match:
        sys.exit(f"{name} is missing")
    return float(match.group(1))


gains = {"SPATCH": exported("cpSPATCHExcessPct"), "colorectal": exported("cpCRCExcessPct"), "ovarian": exported("ovHardGainPct")}
# the colorectal comparator is a raw matrix, so its whole-slide and same-bin gains must agree
if exported("cpCRCExcessPct") != exported("crcHardGainPct"):
    sys.exit("colorectal gain differs between the whole slide and Space Ranger's bins")
examined = exported("exGainPct", EXAMINED)
# the text says STARgrid counts more molecules on every slide
if examined <= 0:
    sys.exit("examined-slide gain is not positive")
match = re.search(r"^% examined: M=([0-9,]+) T=([0-9,]+)", SOURCES, re.M)
target = re.search(r"\\newcommand\{\\exSRMass\}\{([0-9,]+)\}", EXAMINED)
if not match or not target:
    sys.exit("examined-slide M and T, or exSRMass, are missing")
m, t = (int(x.replace(",", "")) for x in match.groups())
split_on_probe_genes = m == int(target.group(1).replace(",", ""))
if split_on_probe_genes and not (f"{100 * (t - m) / m:.2f}" == f"{examined:.2f}" == f"{exported('srcExGapPct', SOURCES):.2f}"):
    sys.exit("the source split of the examined slide gives a different gain from exGainPct")
every = dict(gains, examined=examined)
print("% Generated by make_gain_range_numbers.py from numbers.tex, source_split_numbers.tex and examined_agreement_numbers.tex")
print("% Gain of the HARD field over Space Ranger, counted on the bins in Space Ranger's matrix: "
      + ", ".join(f"{k} {v:.2f}%" for k, v in gains.items()))
print(f"% Over all four slides, adding the examined slide: {examined:.2f}%"
      + ("" if split_on_probe_genes else " (its source split is not yet on the probe set's genes)"))
print(f"\\newcommand{{\\gainSameBinsLo}}{{{min(gains.values()):.1f}}}")
print(f"\\newcommand{{\\gainSameBinsHi}}{{{max(gains.values()):.1f}}}")
print(f"\\newcommand{{\\gainAllLo}}{{{min(every.values()):.1f}}}")
print(f"\\newcommand{{\\gainAllHi}}{{{max(every.values()):.1f}}}")
