#!/usr/bin/env python3
"""Outcome shares of the coordinate audit, by number of edits and by ties (audit_outcome_numbers.tex).

    python3 make_audit_outcome_numbers.py > audit_outcome_numbers.tex

On slide H1-VM2JXXK/A1 every eligible read with a capture location within two
edits per half falls into one of three outcomes: Space Ranger's location is one
of the closest, it is a different location, or Space Ranger assigned none. This
script splits those outcomes by the number of edits to the closest location and
by whether the closest location is unique, from the stratified table of the
July 2026 audit. It follows figures/scripts/sr_audit_half_limit.py of the
record repository and belongs beside it; it is kept here until the record
export adopts it. No number is typed by hand.
"""
import csv
import hashlib
import json
import sys
from collections import defaultdict
from pathlib import Path

INPUTS = Path(__file__).resolve().parents[1] / "paper_results/number_inputs"
STRATA = INPUTS / "edit_strata.tsv"
STRATA_SHA256 = "0a242fa8bc448d6dc795e922c5114e785e6dc62fa2ef0794a9afb7af7e86866e"
TAXONOMY = INPUTS / "disagreement_taxonomy_summary.json"
CANDIDATES = INPUTS / "candidate_preservation_summary.json"

if hashlib.sha256(STRATA.read_bytes()).hexdigest() != STRATA_SHA256:
    sys.exit("edit_strata.tsv does not match its recorded checksum")

by = defaultdict(int)          # (scope, status, edits, unique) -> reads
with open(STRATA) as handle:
    for row in csv.DictReader(handle, delimiter="\t"):
        key = (row["scope"], row["sr_status"], int(row["min_tier"]), row["cardinality"] == "unique")
        by[key] += int(row["read_groups"])


def total(scope=None, status=None, edits=None, unique=None):
    return sum(n for (sc, st, e, u), n in by.items()
               if (scope is None or sc == scope) and (status is None or st == status)
               and (edits is None or e == edits) and (unique is None or u == unique))


headline = json.load(open(TAXONOMY))["headline"]
counts = json.load(open(CANDIDATES))["counts"]
in_range = total()
if in_range != headline["star_candidate_reads"]:
    sys.exit("strata do not sum to the reads with a location in range")
if total(status="sr_unassigned") != headline["sr_unassigned_with_star_candidate"]:
    sys.exit("unassigned reads disagree with the taxonomy summary")
if total(status="sr_outside_minimum") != headline["sr_selected_nonminimum"]:
    sys.exit("different-location reads disagree with the taxonomy summary")
eligible = headline["shared_eligible_reads"]
sr_placed = counts["shared_eligible"] - counts["missing_sr_cb"]      # reads to which Space Ranger assigned a location
sr_only = sr_placed - headline["sr_selected_retained_minimum"] - headline["sr_selected_nonminimum"]

unassigned = total(status="sr_unassigned")
different = total(status="sr_outside_minimum")
other = total(scope="nonoverlap", status="sr_outside_minimum")
tied = total(unique=False)


def pct(n, d, places):
    return f"{100 * n / d:.{places}f}"


out = [
    "% Generated by make_audit_outcome_numbers.py from the July 2026 audit of slide H1-VM2JXXK/A1",
    f"% source: {STRATA.relative_to(INPUTS.parents[1])} (sha256 {STRATA_SHA256})",
    "% Denominator unless stated: eligible reads with a capture location within the edit limit.",
    # reads with a different location that are not the overlap case
    f"\\newcommand{{\\outOtherDifferent}}{{{other:,}}}",
    f"\\newcommand{{\\outOtherDifferentPct}}{{{pct(other, in_range, 3)}}}",
    f"\\newcommand{{\\outOtherShareOfDifferentPct}}{{{pct(other, different, 2)}}}",
    f"\\newcommand{{\\outOtherTwoOrThreeEditsPct}}{{{pct(total('nonoverlap', 'sr_outside_minimum', 2) + total('nonoverlap', 'sr_outside_minimum', 3), other, 1)}}}",
    # reads we assign and Space Ranger does not
    f"\\newcommand{{\\outUnassignedExact}}{{{total(status='sr_unassigned', edits=0):,}}}",
    f"\\newcommand{{\\outUnassignedTwoOrMoreEditsPct}}{{{pct(unassigned - total(status='sr_unassigned', edits=1) - total(status='sr_unassigned', edits=0), unassigned, 1)}}}",
    f"\\newcommand{{\\outUnassignedThreeOrFourEditsPct}}{{{pct(total(status='sr_unassigned', edits=3) + total(status='sr_unassigned', edits=4), unassigned, 1)}}}",
    f"\\newcommand{{\\outUnassignedSingleClosestPct}}{{{pct(total(status='sr_unassigned', unique=True), unassigned, 1)}}}",
]
names = {1: "One", 2: "Two", 3: "Three", 4: "Four"}
places = {1: 3, 2: 2, 3: 1, 4: 1}
for edits in (1, 2, 3, 4):
    out.append(f"\\newcommand{{\\outUnassignedRate{names[edits]}}}{{{pct(total(status='sr_unassigned', edits=edits), total(edits=edits), places[edits])}}}")
out += [
    # the reverse case, as a share of all eligible reads
    f"\\newcommand{{\\outSROnlyPct}}{{{pct(sr_only, eligible, 4)}}}",
    f"\\newcommand{{\\outSROnlyOfSRPct}}{{{pct(sr_only, sr_placed, 4)}}}",
    f"\\newcommand{{\\outSRPlacedAlsoOursPct}}{{{pct(sr_placed - sr_only, sr_placed, 3)}}}",
    f"\\newcommand{{\\outOursAlsoSRPlacedPct}}{{{pct(in_range - unassigned, in_range, 2)}}}",
    # ties
    f"\\newcommand{{\\outTiedPct}}{{{pct(tied, in_range, 1)}}}",
    f"\\newcommand{{\\outTiedSRAmongPct}}{{{pct(total(status='sr_selected_minimum', unique=False), tied, 1)}}}",
    f"\\newcommand{{\\outTiedSRNonePct}}{{{pct(total(status='sr_unassigned', unique=False), tied, 1)}}}",
    f"\\newcommand{{\\outTiedSROtherPct}}{{{pct(total(status='sr_outside_minimum', unique=False), tied, 1)}}}",
]
print("\n".join(out))
print(f"% checks: in range {in_range:,}; eligible {eligible:,}; Space Ranger only {sr_only:,}; tied {tied:,}", file=sys.stderr)
