#!/usr/bin/env python3
"""Lengths the two barcode parts of a read can have under the edit limit (decode_length_numbers.tex).

    python3 make_decode_length_numbers.py > decode_length_numbers.tex

Each listed barcode has one of two lengths, and the decoder allows a number of
edits in each barcode. An insertion lengthens the part of the read that came
from a barcode by one base and a deletion shortens it by one, so the part can
be shorter than the shortest listed barcode, or longer than the longest, by the
edit limit. The listed lengths are read from design_numbers.tex and the limit
from numbers.tex. Kept here until the record export adopts it.
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent


def exported(file, name):
    match = re.search(r"\\newcommand\{\\" + name + r"\}\{([0-9]+)\}", (HERE / file).read_text())
    if not match:
        sys.exit(f"{name} is missing from {file}")
    return int(match.group(1))


limit = exported("numbers.tex", "perHalfED")
print("% Generated by make_decode_length_numbers.py from design_numbers.tex and numbers.tex")
print(f"% Length of the part of a read from each barcode, with up to {limit} edits in that barcode")
for half, macro in (("BCOne", "decBCOne"), ("BCTwo", "decBCTwo")):
    shortest = exported("design_numbers.tex", f"design{half}MinLength")
    longest = exported("design_numbers.tex", f"design{half}MaxLength")
    if not shortest < longest:
        sys.exit(f"{half}: the listed lengths are not two distinct values in order")
    print(f"\\newcommand{{\\{macro}MinLength}}{{{shortest - limit}}}")
    print(f"\\newcommand{{\\{macro}MaxLength}}{{{longest + limit}}}")
# the whole barcode, under the documented total, which is the limit applied to both barcodes
words = {"two": 2, "four": 4, "six": 6}
total_word = re.search(r"\\newcommand\{\\documentedTotalED\}\{(\w+)\}", (HERE / "numbers.tex").read_text())
if not total_word or words.get(total_word.group(1)) != 2 * limit:
    sys.exit("the documented total is not twice the limit for one barcode")
print(f"% Length of the whole barcode of a read, with up to {2 * limit} edits in all")
print(f"\\newcommand{{\\decBarcodeMinLength}}{{{exported('design_numbers.tex', 'designBarcodeMinLength') - 2 * limit}}}")
print(f"\\newcommand{{\\decBarcodeMaxLength}}{{{exported('design_numbers.tex', 'designBarcodeMaxLength') + 2 * limit}}}")
