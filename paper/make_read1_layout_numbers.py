#!/usr/bin/env python3
"""Where the UMI and the barcode lie in Read 1, as the decoder reads them (read1_layout_numbers.tex).

    python3 make_read1_layout_numbers.py > read1_layout_numbers.tex

The UMI length is read from STAR Suite's own source at the cited release (the
commit named in release_numbers.tex): the decoder takes the first bases of
Read 1 as the UMI. The same source gives the range of start positions it tries
for the barcode, which must equal the range exported from the chemistry
definition (design_numbers.tex). Positions count from 0, so a barcode that
follows the UMI directly starts at the offset equal to the UMI length. Set
STAR_SUITE to the checkout if it is not at the default path. Kept here until
the record export adopts it.
"""
import os
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SUITE = os.environ.get("STAR_SUITE", "STAR-suite")


def macro(file, name):
    match = re.search(r"\\newcommand\{\\" + name + r"\}\{([^}]*)\}", (HERE / file).read_text())
    if not match:
        sys.exit(f"{name} is missing from {file}")
    return match.group(1)


def source(commit, path):
    done = subprocess.run(["git", "-C", SUITE, "show", f"{commit}:{path}"], capture_output=True, text=True)
    if done.returncode != 0:
        sys.exit(f"cannot read {path} at {commit} in {SUITE}")
    return done.stdout


commit = macro("release_numbers.tex", "citedReleaseCommit")
decoder = source(commit, "core/legacy/source/SpatialR1Decoder.cpp")
found = re.search(r"bool encodeRawUmi(\d+)\(const char \*sequence, std::size_t length,.*?\n\}", decoder, flags=re.S)
if not found:
    sys.exit("the UMI encoder was not found in the decoder source")
umi = int(found.group(1))
if f"length < {umi}" not in found.group(0) or f"i < {umi}" not in found.group(0):
    sys.exit("the UMI encoder does not read the number of bases its name gives")
pipeline = source(commit, "core/legacy/source/SpatialGexPipeline.cpp")
window = [re.search(r"decoderConfig\.fullStart" + end + r" = (\d+);", pipeline) for end in ("Min", "Max")]
if not all(window):
    sys.exit("the decoder's start window was not found in the pipeline source")
low, high = (int(w.group(1)) for w in window)
if (str(low), str(high)) != (macro("design_numbers.tex", "chemOffsetLo"), macro("design_numbers.tex", "chemOffsetHi")):
    sys.exit("the decoder's start window differs from the range exported from the chemistry definition")
if not low <= umi <= high:
    sys.exit("a barcode that follows the UMI directly would start outside the decoder's start window")
print(f"% Generated by make_read1_layout_numbers.py from STAR Suite at {commit} ({macro('release_numbers.tex', 'citedRelease')})")
print(f"% The decoder reads the first {umi} bases of Read 1 as the UMI and tries barcode starts at offsets {low}-{high}, counted from 0")
print(f"\\newcommand{{\\umiLength}}{{{umi}}}")
