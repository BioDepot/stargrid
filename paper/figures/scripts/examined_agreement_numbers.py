#!/usr/bin/env python3
"""Generate the A1 macros (slide H1-VM2JXXK/A1 against Space Ranger 4.0.1) from the examined-agreement record.

PI, 2026-11-09: A1 is compared on Space Ranger's declared probe target set, as the colorectal and SPATCH slides are.
Formats follow the colorectal macros (crcGenePearson, crcTwoUmPearson, crcSixteenUmPearson, crcEightUmExactPct).
"""
import csv
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
RECORD = ROOT / 'paper_results/examined_agreement_20261027'


def main():
    paths = {'comparison': RECORD / 'target_v1/summary.json', 'off_target': RECORD / 'off_target_mass.tsv'}
    summary = json.loads(paths['comparison'].read_text())
    assert summary['status'] == 'complete'
    hard = {row['scale_um']: row for row in summary['rows'] if row['policy'] == 'postcollapse_hard'}
    assert set(hard) == {2, 8, 16}
    masses = {(row['open_raw_mass'], row['space_ranger_raw_mass']) for row in hard.values()}
    assert len(masses) == 1, 'HARD and Space Ranger masses must not depend on the scale'
    (star, sr), = masses
    assert star == 279777220
    off = {row['slide']: row for row in csv.DictReader(paths['off_target'].open(), delimiter='\t')}
    assert int(off['examined']['target_mass']) == sr
    values = {
        # Seven decimals: at six, as for the colorectal slide, this value would round to 1.
        'exGenePearson': (f"{hard[2]['gene_total_pearson']:.7f}", 'comparison', 'HARD gene totals on the probe target set'),
        'exTwoUmPearson': (f"{hard[2]['bin_total_pearson']:.4f}", 'comparison', 'HARD 2 um bin totals, probe target set'),
        'exEightUmPearson': (f"{hard[8]['bin_total_pearson']:.5f}", 'comparison', 'HARD 8 um bin totals, probe target set'),
        'exSixteenUmPearson': (f"{hard[16]['bin_total_pearson']:.5f}", 'comparison', 'HARD 16 um bin totals, probe target set'),
        'exEightUmExactPct': (f"{100 * hard[8]['exact_entry_fraction']:.1f}", 'comparison',
                              'identical 8 um entries as a share of entries nonzero in either matrix'),
        'exSRMass': (f'{int(sr):,}', 'comparison', 'Space Ranger 4.0.1 molecules on the probe target set'),
        'exStarMass': (f'{int(star):,}', 'comparison', 'HARD 1MM_CR molecules (all on the probe target set)'),
        'exGainPct': (f'{100 * (star - sr) / sr:.2f}', 'comparison', '100*(HARD-SR)/SR on the probe target set'),
        'exTargetGenes': (f"{int(off['examined']['target_features']):,}", 'off_target', 'genes in the declared target set'),
        'exOffTargetPct': (f"{float(off['examined']['off_target_percent_of_whole']):.1f}", 'off_target',
                           "share of Space Ranger's molecules on genes outside the target set"),
        'crcOffTargetPct': (f"{float(off['crc']['off_target_percent_of_whole']):.1f}", 'off_target',
                            "colorectal: share of Space Ranger's molecules on genes outside the target set"),
    }
    lines = ['% Generated by paper/figures/scripts/examined_agreement_numbers.py; do not edit.',
             '% H1-VM2JXXK/A1: STARgrid v1.12.2 HARD against Space Ranger 4.0.1, on the declared probe target set',
             '% (HARD matrix byte-identical to the v1.12.2 run: target_v1/release_identity.txt).']
    for name, (value, key, scope) in values.items():
        path = paths[key]
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        lines.extend([f'% {name}: {path.relative_to(ROOT)}; SHA-256 {digest}; {scope}',
                      '\\newcommand{\\' + name + '}{' + value + '}'])
    output = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / 'paper/examined_agreement_numbers.tex'
    output.write_text('\n'.join(lines) + '\n')
    print(f'Wrote {len(values)} provenance-tagged macros')


if __name__ == '__main__':
    main()
