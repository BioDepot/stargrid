#!/usr/bin/env python3
"""Generate T1 macros only from all nine checked pairs; never modify the manuscript."""
import argparse
import csv
import hashlib
from pathlib import Path
from statistics import median
import math
import os

ROOT = Path(__file__).resolve().parents[3]
SLIDES = {'crc': 'CRC', 'spatch': 'SPATCH', 'ovarian': 'OV'}

def minutes_seconds(seconds):
    value = math.floor(float(seconds) + .5)
    return f'{value // 60}:{value % 60:02d}'

def generate(record):
    source = record / 'pairs.tsv'
    with source.open() as stream:
        rows = list(csv.DictReader(stream, delimiter='\t'))
    assert len(rows) == 9, 'All nine checked pairs are required'
    provenance = f'{os.path.relpath(source, ROOT)}; SHA-256 {hashlib.sha256(source.read_bytes()).hexdigest()}'
    lines = ['% Generated by paper/figures/scripts/timing_numbers.py; do not edit.',
             '% Times are medians over the three runs of each pipeline; speed-up, reduction and CPU share are ratios of these medians.',
             '% Segmentation tail: max(0, mask finish - max(STAR finish, image registration finish, capture-grid finish)).']
    def emit(name, value, detail):
        lines.extend([f'% {name}: {provenance}; {detail}', '\\newcommand{\\'+name+'}{'+value+'}'])
    reductions = []
    fields = {'SR': 'spaceranger_seconds', 'Star': 'stargrid_seconds',
              'StarAlone': 'star_seconds', 'Segmentation': 'segmentation_seconds',
              'SegmentationCritical': 'segmentation_tail_seconds'}
    for slide, label in SLIDES.items():
        group = [r for r in rows if r['slide'] == slide]
        assert len(group) == 3 and {int(r['pair']) for r in group} == {1,2,3}
        for suffix, column in fields.items():
            values = [float(r[column]) for r in group]
            assert all(math.isfinite(v) for v in values)
            fmt = minutes_seconds
            name = 'time'+label+suffix
            emit(name, fmt(median(values)), f'{slide}; median {column}')
            emit(name+'Min', fmt(min(values)), f'{slide}; minimum {column}')
            emit(name+'Max', fmt(max(values)), f'{slide}; maximum {column}')
            emit(name+'Range', fmt(min(values))+'--'+fmt(max(values)), f'{slide}; range {column}')
        # One basis throughout (PI, 2026-11-09): the runs of the two pipelines are not matched, so every
        # comparison is a ratio of the medians, never a median of run-by-run ratios.
        reduction = 100 * (1 - median(float(r['stargrid_seconds']) for r in group) / median(float(r['spaceranger_seconds']) for r in group))
        emit('time'+label+'LessPct', f'{reduction:.1f}', f'{slide}; 100*(1 - median stargrid_seconds / median spaceranger_seconds)')
        reductions.append(reduction)
    emit('timeLessLo', f'{min(reductions):.1f}', 'lowest slide reduction (ratio of medians, %)')
    emit('timeLessHi', f'{max(reductions):.1f}', 'highest slide reduction (ratio of medians, %)')
    # Speed-up (Space Ranger time / STARgrid time) and STARgrid's share of Space Ranger's processor
    # time (cgroup user + system), each a ratio of the medians over the three runs of each pipeline.
    runs_source = record / 'accepted_runs.tsv'
    with runs_source.open() as stream:
        runs = {r['run']: r for r in csv.DictReader(stream, delimiter='\t')}
    cpu = lambda run: float(runs[run]['cpu_user_seconds']) + float(runs[run]['cpu_system_seconds'])
    pair_provenance = provenance
    runs_provenance = f'{os.path.relpath(runs_source, ROOT)}; SHA-256 {hashlib.sha256(runs_source.read_bytes()).hexdigest()}'
    folds, cpu_shares = [], []
    for slide, label in SLIDES.items():
        group = [r for r in rows if r['slide'] == slide]
        provenance = pair_provenance
        # Speed-up is the ratio of the two medians (PI, 2026-11-09), not the median of the paired ratios.
        fold = median(float(r['spaceranger_seconds']) for r in group) / median(float(r['stargrid_seconds']) for r in group)
        name = 'time'+label+'Fold'
        emit(name, f'{fold:.1f}', f'{slide}; median spaceranger_seconds / median stargrid_seconds')
        folds.append(fold)
        provenance = f'{pair_provenance}; {runs_provenance}'
        assert all(runs[r[k]]['accepted'] == 'True' for r in group for k in ('spaceranger_run', 'stargrid_run'))
        share = 100 * median(cpu(r['stargrid_run']) for r in group) / median(cpu(r['spaceranger_run']) for r in group)
        assert math.isfinite(share) and share > 0
        emit('time'+label+'CPUPct', f'{share:.0f}', f'{slide}; median STARgrid / median Space Ranger cgroup CPU seconds (%)')
        cpu_shares.append(share)
    provenance = pair_provenance
    emit('timeFoldLo', f'{min(folds):.1f}', 'lowest slide speed-up (ratio of medians)')
    emit('timeFoldHi', f'{max(folds):.1f}', 'highest slide speed-up (ratio of medians)')
    provenance = f'{pair_provenance}; {runs_provenance}'
    emit('timeCPUPctLo', f'{min(cpu_shares):.0f}', 'lowest slide CPU share (ratio of medians, %)')
    emit('timeCPUPctHi', f'{max(cpu_shares):.0f}', 'highest slide CPU share (ratio of medians, %)')
    environment = record / 'timing_environment.json'
    import json
    spec = json.loads(environment.read_text())
    provenance = f'{os.path.relpath(environment, ROOT)}; SHA-256 {hashlib.sha256(environment.read_bytes()).hexdigest()}'
    assert spec['host'] == '<gpu-host>' and spec['release'] == 'v1.12.2'
    assert spec['cpu_set'] == '0-15,24-39' and spec['logical_cpus'] == 32
    for name, value, detail in [('timeHost',spec['host'],'timing host'),
        ('timeCPU',spec['cpu_model'],'CPU model'),('timeCPUSet','0--15,24--39','logical CPU set'),
        ('timeCPUs','32','logical CPUs'),('timeCores','16','physical cores'),
        ('timeGPU',spec['gpu_model'],'Cellpose GPU'),('timeGPUSharing',spec.get('gpu_sharing','shared with an idle Gemma 4 vLLM server'),spec['llm_sharing']),
        ('timeSTARRelease',spec['release'],'official workflow release'),('timeSpaceRangerRelease','4.1.0','Space Ranger version')]:
        emit(name,value,detail)
    return '\n'.join(lines)+'\n'

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--record', type=Path, default=ROOT/'paper_results/timing_20261108_cpp')
    parser.add_argument('--output', type=Path)
    args = parser.parse_args()
    text = generate(args.record)
    if args.output:
        args.output.write_text(text)
    else:
        print(text,end='')
