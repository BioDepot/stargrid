#!/usr/bin/env python3
"""Generate B3 macros exclusively from a complete, gated release examination.

Default input: paper_results/release_examination_v1_12_2_20261105/results.json (the rerun with the
cited release, v1.12.2; the v1.9.5.a record of 2026-10-25 gives the same values).
Default output: paper/examination_release_numbers.tex. The ovarian examination (B3-Ov, macros ending in Ov)
is written with --record and --catalogue of paper_results/release_examination_ovarian_v1_12_2_20261109 and
--output paper/ovarian_examination_numbers.tex. Incomplete/failed gates
produce an explicit LaTeX error with per-macro unavailability and exit status 2.
July/printed comparison columns can never supply a missing release value.
"""
import argparse
import hashlib
import json
import re
from pathlib import Path

RELEASE = '2ca281c96f3dd2b9d596da1991b397fd05f9f73d'
GRID_INDEX = re.compile(r'case(?:One|Two)(?:Closest|SR)(?:Row|Column)')
EXPECTED = {'H1-VM2JXXK/A1': dict(eligible_reads=707409359, native_M=277918688,
                                  release_T=279777220, joined_rows=707409359,
                                  missing_joined_rows=0, duplicate_joined_rows=0),
            'H1-YQJBZ7X/D1': dict(eligible_reads=392509264, native_M=187552358,
                                  release_T=201888275, joined_rows=392509264)}
# Each record keeps the unchanged protocol under a dated name
PROTOCOL = {'release_examination_v1_12_2_20261105/protocol.md':
            'release_examination_v1_12_2_20261105/protocol_20261025_unchanged.md',
            'release_examination_ovarian_v1_12_2_20261109/protocol.md':
            'release_examination_ovarian_v1_12_2_20261109/protocol_20261026_unchanged.md'}

def render(record, catalogue, source_sha256):
    names = [r['macro'] for r in catalogue]
    if len(set(names)) != len(names) or not names:
        raise ValueError('Macro catalogue must contain unique names')
    if any(not re.fullmatch(r'[A-Za-z][A-Za-z0-9]*', n) for n in names):
        raise ValueError('Invalid macro name')
    values = record.get('macro_values', {})
    expected = EXPECTED[record.get('slide', 'H1-VM2JXXK/A1')]     # the A1 record has no slide field
    ready = (record.get('status') == 'complete'
             and record.get('release_revision') == RELEASE
             and record.get('all_gates_passed') is True
             and all(record.get('gates', {}).get(k) == v for k, v in expected.items())
             and set(values) == set(names))
    if ready:
        for name in names:
            row = values[name]
            if (not re.fullmatch(r'-?[0-9]+(?:,[0-9]{3})*(?:\.[0-9]+)?', str(row.get('primary', '')))
                    or not re.fullmatch(r'[a-f0-9]{64}', row.get('source_sha256', ''))
                    or not row.get('source') or not row.get('field')
                    or not row.get('universe')):
                raise ValueError('Missing numeric value or provenance for ' + name)
    lines = ['% Generated by figures/scripts/examination_release_numbers.py.',
             '% B3 official ' + record.get('release', '').split()[-1] + '; raw Read 1; production hard/1MM_CR.',
             '% Result record SHA-256: ' + source_sha256]
    if not ready:
        lines += ['% B3 is incomplete or a mandatory gate failed. No replacement values are defined.',
                  r'\PackageError{release-examination}{B3 release examination is not complete}{Use the B3 results note; do not substitute historical values.}']
        for name in sorted(names):
            lines.append('% ' + name + ': UNAVAILABLE; result_record_sha256=' + source_sha256)
        return '\n'.join(lines) + '\n', False
    release = record.get('release', '').split()[-1]      # "official v1.9.5.a" -> "v1.9.5.a"
    if not re.fullmatch(r'v[0-9]+(?:\.[0-9a-z]+)+', release):
        raise ValueError('Release name missing from the result record')
    suffix = 'Ov' if all(n.endswith('Ov') for n in names) else ''     # B3-Ov macros carry Ov
    lines += [f'% examinationRelease{suffix}: results.json; release',
              '\\newcommand{\\examinationRelease' + suffix + '}{' + release + '}']
    for name in sorted(names):
        row = values[name]
        provenance = '; '.join(str(row[k]).replace('\n', ' ') for k in
                               ('source', 'source_sha256', 'field', 'universe'))
        for recorded, kept in PROTOCOL.items():
            provenance = provenance.replace(recorded, kept)
        lines.append('% ' + name + ': ' + provenance)
        value = str(row['primary'])
        if GRID_INDEX.fullmatch(name):        # grid row and column of the worked reads: indices, not counts
            value = value.replace(',', '')
        lines.append('\\newcommand{\\' + name + '}{' + value + '}')
    return '\n'.join(lines) + '\n', True

def main():
    root = Path(__file__).resolve().parents[3]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--record', type=Path, default=root/'paper_results/release_examination_v1_12_2_20261105/results.json')
    parser.add_argument('--catalogue', type=Path, default=root/'paper_results/release_examination_v1_12_2_20261105/macro_catalogue.json')
    parser.add_argument('--output', type=Path, default=root/'paper/examination_release_numbers.tex')
    args = parser.parse_args()
    content = args.record.read_bytes()
    text, ready = render(json.loads(content), json.loads(args.catalogue.read_text()), hashlib.sha256(content).hexdigest())
    args.output.write_text(text)
    return 0 if ready else 2

if __name__ == '__main__':
    raise SystemExit(main())
