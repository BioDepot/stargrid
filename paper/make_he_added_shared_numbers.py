#!/usr/bin/env python3
"""In-cell fraction and cell ROC AUC of the shared and added counts (he_added_shared_numbers.tex).

    python3 make_he_added_shared_numbers.py > he_added_shared_numbers.tex

The table of added against shared counts needs both measures for both
components on all three slides. The record export supplies them for the ovarian
dataset, and the added-count ROC AUC and the differences in in-cell fraction
for the two Flex slides. This script reads the remaining values from the same
H&E table, rescored after the SPATCH correction was refitted, and checks that
every value the export already supplies agrees with it. Kept here until the
record export adopts it. No number is typed by hand.
"""
import csv
import hashlib
import re
import sys
from pathlib import Path

TABLE = Path(__file__).resolve().parents[1] / "paper_results/spatch_rescore_ratio_20261109/he_shared_excess.tsv"
TABLE_SHA256 = "a25ade006b40ff886592fea05381a68354d420f04c9582273637c127d115fa93"
NUMBERS = Path(__file__).resolve().parent / "numbers.tex"

if hashlib.sha256(TABLE.read_bytes()).hexdigest() != TABLE_SHA256:
    sys.exit("he_shared_excess.tsv does not match its recorded checksum")
auc, in_cell, area = {}, {}, {}
with open(TABLE) as handle:
    for row in csv.DictReader(handle, delimiter="\t"):
        if row["method"] == "hard":
            key = (row["dataset"], row["component"])
            auc[key] = float(row["cell_roc_auc"])
            in_cell[key] = float(row["cell_mass_fraction"])
            # the table gives the in-cell fraction divided by the share of area inside cells
            area[key] = in_cell[key] / float(row["cell_area_normalized_enrichment"])


def exported(name):
    match = re.search(r"\\newcommand\{\\" + name + r"\}\{([0-9.]+)\}", NUMBERS.read_text())
    if not match:
        sys.exit(f"{name} is missing from numbers.tex")
    return match.group(1)


def check(name, value, places):
    if exported(name) != f"{value:.{places}f}":
        sys.exit(f"{name} = {exported(name)} disagrees with the table ({value:.{places}f})")


# every value the export already supplies must be the same table's
check("cpCRCStarOnlyCellAUC", auc[("CRC", "star_excess")], 3)
check("cpSPATCHStarOnlyCellAUC", auc[("SPATCH", "star_excess")], 3)
check("heExcessAUC", auc[("OVARIAN_GEX", "star_excess")], 3)
check("heSharedAUC", auc[("OVARIAN_GEX", "shared")], 3)
check("heExcessInCell", in_cell[("OVARIAN_GEX", "star_excess")], 3)
check("heSharedInCell", in_cell[("OVARIAN_GEX", "shared")], 3)
check("crcExcessDeficitPP", 100 * (in_cell[("CRC", "shared")] - in_cell[("CRC", "star_excess")]), 2)
check("spatchExcessDeficitPP", 100 * (in_cell[("SPATCH", "shared")] - in_cell[("SPATCH", "star_excess")]), 2)
check("heExcessDeficitPP", 100 * (in_cell[("OVARIAN_GEX", "shared")] - in_cell[("OVARIAN_GEX", "star_excess")]), 2)

print("% Generated by make_he_added_shared_numbers.py from the record's H&E table of the three slides")
print(f"% source: paper_results/spatch_rescore_ratio_20261109/he_shared_excess.tsv (sha256 {TABLE_SHA256})")
print("% HARD field, 8 um bins: share of counts in bins inside cells, and ROC AUC for ranking those bins above the rest")
# share of bin area inside cells: what the in-cell fraction would be if counts were placed at random
for slide, name in (("CRC", "CRC"), ("SPATCH", "SPATCH"), ("OVARIAN_GEX", "Ovarian")):
    if abs(area[(slide, "shared")] - area[(slide, "star_excess")]) > 1e-9:
        sys.exit(f"{slide}: the two components imply different cell areas")
    print(f"\\newcommand{{\\he{name}CellArea}}{{{area[(slide, 'shared')]:.3f}}}")
for slide, name in (("CRC", "CRC"), ("SPATCH", "SPATCH")):
    print(f"\\newcommand{{\\he{name}SharedInCell}}{{{in_cell[(slide, 'shared')]:.3f}}}")
    print(f"\\newcommand{{\\he{name}AddedInCell}}{{{in_cell[(slide, 'star_excess')]:.3f}}}")
    print(f"\\newcommand{{\\he{name}SharedAUC}}{{{auc[(slide, 'shared')]:.3f}}}")
